// gensyscallnames writes syscallnames_<arch>.go, mapping each syscall number
// of the architectures the tracer runs on, and of their 32-bit ABIs, to its
// name, from the SYS_ constants golang.org/x/sys/unix holds.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var sysConst = regexp.MustCompile(`(?m)^\s*SYS_([A-Z0-9_]+)\s*=\s*(\d+)\s*$`)

// targets maps each GOARCH the tracer builds for to its own syscall table
// and its 32-bit one.
var targets = map[string][2]string{
	"amd64": {"amd64", "386"},
	"arm64": {"arm64", "arm"},
}

func main() {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "golang.org/x/sys").Output()
	if err != nil {
		fail(fmt.Errorf("locate golang.org/x/sys: %w", err))
	}
	dir := filepath.Join(strings.TrimSpace(string(out)), "unix")
	for goarch, tables := range targets {
		native, err := names(dir, tables[0])
		if err != nil {
			fail(err)
		}
		compat, err := names(dir, tables[1])
		if err != nil {
			fail(err)
		}
		var b bytes.Buffer
		fmt.Fprintf(&b, "// Code generated by gensyscallnames; DO NOT EDIT.\n\npackage main\n\n")
		writeMap(&b, "syscallNames", native)
		writeMap(&b, "compatSyscallNames", compat)
		src, err := format.Source(b.Bytes())
		if err != nil {
			fail(err)
		}
		if err := os.WriteFile("syscallnames_"+goarch+".go", src, 0o644); err != nil {
			fail(err)
		}
	}
}

func names(dir, arch string) (map[int64]string, error) {
	src, err := os.ReadFile(filepath.Join(dir, "zsysnum_linux_"+arch+".go"))
	if err != nil {
		return nil, err
	}
	m := map[int64]string{}
	for _, c := range sysConst.FindAllStringSubmatch(string(src), -1) {
		n, err := strconv.ParseInt(c[2], 10, 64)
		if err != nil {
			return nil, err
		}
		m[n] = strings.ToLower(c[1])
	}
	return m, nil
}

func writeMap(b *bytes.Buffer, name string, m map[int64]string) {
	nrs := make([]int64, 0, len(m))
	for n := range m {
		nrs = append(nrs, n)
	}
	sort.Slice(nrs, func(i, j int) bool { return nrs[i] < nrs[j] })
	fmt.Fprintf(b, "var %s = map[int64]string{\n", name)
	for _, n := range nrs {
		fmt.Fprintf(b, "%d: %q,\n", n, m[n])
	}
	fmt.Fprintf(b, "}\n\n")
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gensyscallnames:", err)
	os.Exit(1)
}
